#!/usr/bin/env bun
/**
 * Scan ~/Documents/projects for cheap signals about each project.
 *
 * Read-only: it runs `git log` / `git ls-files` and reads only README and
 * package.json (plus a few small config files for a live URL). It never
 * builds, installs or edits anything in the scanned projects.
 *
 * Usage:
 *   bun scripts/scan-projects.ts [root] [--json] [--md] [--github <user>]
 *   (default root: ~/Documents/projects, default output: --md)
 *
 * --github <user> also reads the user's public repos from the GitHub API
 * (read-only, unauthenticated), adds each repo's GitHub Pages URL when it
 * answers, and lists public repos that have no local clone.
 */
import { readdirSync, statSync, existsSync, readFileSync, openSync, readSync, closeSync } from "node:fs";
import { join, relative, basename } from "node:path";
import { homedir } from "node:os";

const args = process.argv.slice(2);
const asJson = args.includes("--json");
const ghUser = args.includes("--github") ? args[args.indexOf("--github") + 1] : undefined;
const ROOT_ARG = args.find((a, i) => !a.startsWith("--") && args[i - 1] !== "--github");

const SKIP = new Set(["node_modules", ".git", "dist", "build", "target", ".astro", ".next", "__pycache__", ".cursor", ".DS_Store"]);
const MARKERS = [".git", "package.json", "README.md", "readme.md", "README", "Cargo.toml", "pyproject.toml", "setup.py", "go.mod", "index.html", "requirements.txt"];
const FRAMEWORKS = [
  "astro", "react", "next", "vite", "electron", "svelte", "vue", "solid-js", "preact", "three",
  "@tanstack/react-router", "react-router", "tailwindcss", "storybook", "express", "hono", "wrangler",
  "pixi.js", "phaser", "d3", "framer-motion", "@mdx-js/react", "react-scripts",
];
// READMEs left as generated by a starter (Astro, CRA, Next, bun init, TanStack)
const BOILERPLATE = /Astro Starter Kit|Getting Started with Create React App|create-next-app|bun-react(-tailwind)?-template|To install dependencies:|Welcome to your new TanStack app/;
const ROOT = ROOT_ARG ?? join(homedir(), "Documents/projects");
const MAX_READ = 16 * 1024; // never read more than this from any file

type Project = {
  path: string; // relative to ROOT
  group: string;
  name: string;
  gitOwn: boolean; // has its own repo (vs. inside a parent repo or none)
  remote?: string;
  firstCommit?: string;
  lastCommit?: string;
  commits?: number;
  trackedFiles?: number;
  lastActivity: string; // last commit, else newest top-level mtime
  readmeTitle?: string;
  boilerplateReadme: boolean; // README is still the starter template's
  readmeSummary?: string;
  pkgName?: string;
  pkgDescription?: string;
  frameworks: string[];
  liveUrls: string[];
  deployWorkflow: boolean;
  hasDist: boolean;
};

function readHead(file: string, bytes = MAX_READ): string | undefined {
  try {
    const st = statSync(file);
    if (!st.isFile()) return;
    const fd = openSync(file, "r");
    const buf = Buffer.alloc(Math.min(bytes, st.size));
    readSync(fd, buf, 0, buf.length, 0);
    closeSync(fd);
    return buf.toString("utf8");
  } catch {
    return;
  }
}

function git(dir: string, ...cmd: string[]): string | undefined {
  const r = Bun.spawnSync(["git", "-C", dir, ...cmd], { stderr: "ignore" });
  if (r.exitCode !== 0) return;
  return r.stdout.toString().trim();
}

function children(dir: string): string[] {
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isDirectory() && !SKIP.has(d.name) && !d.name.startsWith("."))
      .map((d) => join(dir, d.name));
  } catch {
    return [];
  }
}

function hasMarkers(dir: string): boolean {
  if (MARKERS.some((m) => existsSync(join(dir, m)))) return true;
  try {
    // loose source files at the top level (e.g. a single astrocarto.py, hello.go)
    return readdirSync(dir).some((f) => /\.(py|go|rs|ts|js|html)$/.test(f));
  } catch {
    return false;
  }
}

/** Folders that group projects: no markers of their own, but children that have them. */
function isGroup(dir: string): boolean {
  if (existsSync(join(dir, ".git")) || existsSync(join(dir, "package.json"))) return false;
  const kids = children(dir);
  return kids.length > 0 && kids.filter(hasMarkers).length >= Math.max(1, Math.ceil(kids.length / 3));
}

function discover(dir: string, depth = 0): string[] {
  const out: string[] = [];
  for (const kid of children(dir)) {
    if (depth < 2 && isGroup(kid)) out.push(...discover(kid, depth + 1));
    else if (hasMarkers(kid) || children(kid).length) out.push(kid);
  }
  return out;
}

function parseReadme(dir: string) {
  const file = ["README.md", "readme.md", "Readme.md", "README"].map((f) => join(dir, f)).find(existsSync);
  const text = file && readHead(file);
  if (!text) return {};
  const lines = text.split("\n");
  const title = lines.find((l) => /^#\s+/.test(l))?.replace(/^#+\s*/, "").trim();
  // first paragraph of prose: skip headings, badges, images, html, code fences
  let para: string[] = [];
  let inFence = false;
  for (const l of lines) {
    if (l.trim().startsWith("```")) { inFence = !inFence; continue; }
    if (inFence) continue;
    const t = l.trim();
    if (!t) { if (para.length) break; continue; }
    if (/^(#|!\[|\[!\[|<|---|\|)/.test(t)) { if (para.length) break; continue; }
    para.push(t);
  }
  let summary = para.join(" ").replace(/\s+/g, " ");
  if (summary.length > 160) summary = summary.slice(0, 157) + "…";
  const boilerplate = BOILERPLATE.test(text.slice(0, 600));
  return { title, summary: summary || undefined, text, boilerplate };
}

function liveUrls(dir: string, readme?: string): string[] {
  const urls = new Set<string>();
  for (const cfg of ["astro.config.mjs", "astro.config.ts", "astro.config.js"]) {
    const site = readHead(join(dir, cfg))?.match(/site\s*:\s*["'`]([^"'`]+)["'`]/)?.[1];
    if (site) urls.add(site.replace(/\/?$/, "/"));
  }
  const cname = readHead(join(dir, "public/CNAME")) ?? readHead(join(dir, "CNAME"));
  if (cname?.trim()) urls.add("https://" + cname.trim().split("\n")[0] + "/");
  for (const m of readme?.matchAll(/https?:\/\/[\w.-]+\.(?:nefzen\.dev|github\.io|workers\.dev|pages\.dev|vercel\.app|netlify\.app)[^\s)"'>]*/g) ?? [])
    if (!/facebook\.github\.io/.test(m[0])) urls.add(new URL(m[0].split("]")[0]).origin + new URL(m[0].split("]")[0]).pathname.replace(/[^/]*\.\w+$/, ""));
  // Cloudflare Workers: wrangler name → <name>.<account>.workers.dev (account subdomain guessed)
  for (const cfg of ["wrangler.jsonc", "wrangler.json", "wrangler.toml"]) {
    const name = readHead(join(dir, cfg))?.match(/"?name"?\s*[:=]\s*["']([^"']+)["']/)?.[1];
    if (name) urls.add(`https://${name}.nefzen.workers.dev (wrangler, guessed)`);
  }
  return [...urls];
}

function mtimeNewest(dir: string): Date {
  let newest = statSync(dir).mtime;
  try {
    for (const f of readdirSync(dir)) {
      if (SKIP.has(f)) continue;
      const m = statSync(join(dir, f)).mtime;
      if (m > newest) newest = m;
    }
  } catch {}
  return newest;
}

function scan(dir: string): Project {
  const rel = relative(ROOT, dir);
  const group = rel.includes("/") ? rel.split("/").slice(0, -1).join("/") : "(top)";
  // only count a repo rooted here, never a parent repo the folder happens to sit in
  const gitOwn = existsSync(join(dir, ".git")) && !!git(dir, "rev-parse", "--show-toplevel");
  const p: Project = {
    path: rel, group, name: basename(dir), gitOwn, frameworks: [], liveUrls: [], boilerplateReadme: false,
    lastActivity: "", deployWorkflow: false, hasDist: existsSync(join(dir, "dist")),
  };

  if (gitOwn) {
    p.remote = git(dir, "remote", "get-url", "origin");
    const dates = git(dir, "log", "--format=%cs");
    if (dates) {
      const ds = dates.split("\n");
      p.commits = ds.length;
      p.lastCommit = ds[0];
      p.firstCommit = ds[ds.length - 1];
    }
    p.trackedFiles = git(dir, "ls-files")?.split("\n").filter(Boolean).length;
  }
  p.lastActivity = p.lastCommit ?? mtimeNewest(dir).toISOString().slice(0, 10);

  const rd = parseReadme(dir);
  p.boilerplateReadme = !!rd.boilerplate;
  if (!p.boilerplateReadme) {
    p.readmeTitle = rd.title;
    p.readmeSummary = rd.summary;
  }

  const pkgText = readHead(join(dir, "package.json"));
  if (pkgText) {
    try {
      const pkg = JSON.parse(pkgText);
      p.pkgName = pkg.name;
      p.pkgDescription = pkg.description;
      const deps = { ...pkg.dependencies, ...pkg.devDependencies };
      p.frameworks = FRAMEWORKS.filter((f) => f in deps);
    } catch {}
  }

  p.liveUrls = liveUrls(dir, rd.text);
  try {
    p.deployWorkflow = readdirSync(join(dir, ".github/workflows")).some((f) => /\.ya?ml$/.test(f));
  } catch {}
  return p;
}

const projects = discover(ROOT).map(scan);

type GhRepo = { name: string; fork: boolean; has_pages: boolean; homepage: string | null; pushed_at: string; created_at: string; description: string | null; language: string | null; html_url: string };

/** Final URL after redirects, or undefined when it doesn't answer 200. */
async function probe(url: string): Promise<string | undefined> {
  try {
    const r = await fetch(url, { redirect: "follow", signal: AbortSignal.timeout(8000) });
    return r.ok ? r.url : undefined;
  } catch {
    return;
  }
}

if (ghUser) {
  const res = await fetch(`https://api.github.com/users/${ghUser}/repos?per_page=100&sort=pushed`, {
    headers: { "User-Agent": "scan-projects" },
  });
  const repos: GhRepo[] = res.ok ? await res.json() : [];
  if (!res.ok) console.error(`GitHub API: ${res.status} ${res.statusText}`);
  const slug = (r?: string) => r?.match(/github\.com[:/]([^/]+\/[^/.]+)/)?.[1]?.toLowerCase();
  await Promise.all(
    repos.filter((r) => !r.fork).map(async (r) => {
      const full = `${ghUser}/${r.name}`.toLowerCase();
      const urls: string[] = [];
      if (r.has_pages) {
        const live = await probe(`https://${ghUser.toLowerCase()}.github.io/${r.name}/`);
        if (live) urls.push(live);
      }
      if (r.homepage) urls.push(r.homepage);
      const local = projects.filter((p) => slug(p.remote) === full);
      for (const p of local) for (const u of urls) if (!p.liveUrls.some((x) => x.startsWith(u.replace(/\/$/, "")))) p.liveUrls.push(u + " (GitHub)");
      if (!local.length)
        projects.push({
          path: `github:${r.name}`, group: "github", name: r.name, gitOwn: false, remote: r.html_url,
          firstCommit: r.created_at.slice(0, 10), lastCommit: r.pushed_at.slice(0, 10), lastActivity: r.pushed_at.slice(0, 10),
          readmeSummary: r.description ?? undefined, boilerplateReadme: false,
          frameworks: r.language ? [r.language] : [], liveUrls: urls.map((u) => u + " (GitHub)"),
          deployWorkflow: false, hasDist: false,
        });
    }),
  );
}

projects.sort((a, b) => b.lastActivity.localeCompare(a.lastActivity));

if (asJson) {
  console.log(JSON.stringify(projects, null, 2));
} else {
  const esc = (s?: string) => (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
  const shortRemote = (r?: string) => r?.replace(/^(https:\/\/|git@)github\.com[:/]/, "gh:").replace(/\.git$/, "") ?? "";
  console.log("| Project | Last activity | First commit | Commits | Files | Stack | Live / deploy | Remote | README / description |");
  console.log("|---|---|---|---|---|---|---|---|---|");
  for (const p of projects) {
    const deploy = [
      ...p.liveUrls,
      p.deployWorkflow ? "workflow" : "",
      p.hasDist ? "dist/" : "",
    ].filter(Boolean).join("<br>");
    const about = p.boilerplateReadme
      ? `_(starter README)_${p.pkgDescription ? " — " + p.pkgDescription : ""}`
      : [p.readmeTitle && `**${p.readmeTitle}**`, p.readmeSummary ?? p.pkgDescription].filter(Boolean).join(" — ");
    console.log(
      `| \`${p.path}\` | ${p.lastActivity}${p.lastCommit ? "" : " (mtime)"} | ${p.firstCommit ?? ""} | ${p.commits ?? ""} | ${p.trackedFiles ?? ""} | ${p.frameworks.join(", ")} | ${esc(deploy)} | ${esc(shortRemote(p.remote))} | ${esc(about)} |`,
    );
  }
}
